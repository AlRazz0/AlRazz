async function cleanupFixtures(products, designs) {
  const statements = [];
  // IDs are generated by this test run, never from a database search or user input.
  for (const id of products) assert.match(id, /^api-test-[a-z0-9-]+$/);
  for (const id of designs) assert.match(id, /^[a-f0-9-]{36}$/);
  if (products.length)
    statements.push(
      `DELETE FROM products WHERE id IN (${products.map((id) => `'${id}'`).join(",")})`,
    );
  if (designs.length)
    statements.push(
      `DELETE FROM designs WHERE id IN (${designs.map((id) => `'${id}'`).join(",")})`,
    );
  if (!statements.length) return;
  await promisify(execFile)(
    process.execPath,
    [
      fileURLToPath(
        new URL("../node_modules/wrangler/bin/wrangler.js", import.meta.url),
      ),
      "d1",
      "execute",
      "alrazz-db",
      "--local",
      "--command",
      statements.join(";"),
      "--json",
    ],
    {
      cwd: fileURLToPath(new URL("../", import.meta.url)),
      windowsHide: true,
      timeout: 30000,
    },
  );
}

class Client {
  constructor(ip = "203.0.113.81") {
    this.cookies = new Map();
    this.ip = ip;
  }
  async request(path, data, extraHeaders = {}) {
    const response = await fetch(base + path, {
      method: data === undefined ? "GET" : "POST",
      headers: {
        ...(data === undefined
          ? {}
          : { "Content-Type": "application/json", Origin: base }),
        Cookie: [...this.cookies].map(([k, v]) => k + "=" + v).join("; "),
        "CF-Connecting-IP": this.ip,
        ...extraHeaders,
      },
      body: data === undefined ? undefined : JSON.stringify(data),
    });
    for (const entry of response.headers.getSetCookie()) {
      const pair = entry.split(";")[0];
      const index = pair.indexOf("=");
      this.cookies.set(pair.slice(0, index), pair.slice(index + 1));
    }
    return { response, status: response.status, data: await response.json() };
  }
  get(action) {
    return this.request("/api/store?action=" + action);
  }
  post(data) {
    return this.request("/api/store", data);
  }
  quote(data) {
    return this.request("/api/quote", data);
  }
}

function publicOnly(value) {
  const denied = [
    "basePrice",
    "margin",
    "materialRate",
    "edgeRate",
    "doorHardware",
    "breakdown",
    "owner_hash",
    "snapshot",
    "SESSION_SECRET",
    "ADMIN_PASSWORD",
  ];
  const visit = (object) => {
    if (!object || typeof object !== "object") return;
    for (const [key, item] of Object.entries(object)) {
      assert.ok(
        !denied.includes(key),
        `El dato privado ${key} salió en la respuesta pública.`,
      );
      visit(item);
    }
  };
  visit(value);
}

test("API persistente: autorización, catálogo, concurrencia, cotización y diseños inmutables", async (t) => {
  const fixtureProducts = [],
    fixtureDesigns = [];
  t.after(() => cleanupFixtures(fixtureProducts, fixtureDesigns));
  const staff = new Client();
  const visitor = new Client("203.0.113.82");
  const stranger = new Client("203.0.113.83");
  const state = await staff.get("admin");
  assert.deepEqual(state.data, { admin: false, configured: true });
  assert.equal(
    (await visitor.post({ op: "product", product: {} })).status,
    401,
  );

  const session = await staff.post({ op: "login", password });
  assert.equal(session.status, 200);
  assert.match(session.response.headers.get("set-cookie"), /HttpOnly/);
  assert.match(session.response.headers.get("set-cookie"), /SameSite=Lax/);
  const forged = new Client("203.0.113.84");
  for (const [key, token] of staff.cookies)
    forged.cookies.set(
      key,
      token.slice(0, -1) + (token.endsWith("0") ? "1" : "0"),
    );
  assert.equal(
    (await forged.get("admin")).data.admin,
    false,
    "Una firma de sesión modificada nunca da acceso.",
  );
  assert.equal(
    (await forged.post({ op: "settings", settings: {}, version: 1 })).status,
    401,
  );
  let dashboard = (await staff.get("admin")).data;
  assert.equal(dashboard.admin, true);
  assert.ok(dashboard.settings.materials.length > 0);
  const model = dashboard.products.find((p) => p.active);
  assert.ok(model, "Se requiere al menos un modelo publicado para la prueba.");

  const catalog = await visitor.get("catalog");
  assert.equal(catalog.status, 200);
  publicOnly(catalog.data);
  assert.ok(catalog.data.products[0].preview.panels.length > 0);
  assert.equal(catalog.data.settings.materials[0].price, undefined);
  const quoteInput = { productId: model.id, config: model.defaults };
  const quote = await visitor.quote(quoteInput);
  assert.equal(quote.status, 200);
  publicOnly(quote.data);
  assert.ok(Number.isFinite(quote.data.price) && quote.data.price > 0);
  assert.ok(quote.data.panels.every((p) => p.thickness === 18));
  assert.equal(
    (
      await visitor.quote({
        ...quoteInput,
        config: { ...model.defaults, width: 123 },
      })
    ).status,
    400,
  );
  assert.equal(
    (
      await visitor.quote({
        ...quoteInput,
        config: { ...model.defaults, finish: "does-not-exist" },
      })
    ).status,
    400,
  );
  assert.equal(
    (
      await visitor.request(
        "/api/store",
        { op: "save-design", ...quoteInput },
        { Origin: "https://example.invalid" },
      )
    ).status,
    403,
  );

  const id = "api-test-" + randomUUID();
  fixtureProducts.push(id);
  const created = await staff.post({
    op: "product",
    product: { ...model, id, name: "Prueba automatizada", active: true },
    expectedVersion: 0,
  });
  assert.equal(created.status, 201);
  assert.equal(
    created.data.product.active,
    false,
    "Todo modelo nuevo debe comenzar como borrador.",
  );
  let current = created.data.product;
  assert.equal(
    (await staff.post({ op: "product", product: current, expectedVersion: 0 }))
      .status,
    409,
  );
  assert.ok(
    !(await visitor.get("catalog")).data.products.some((p) => p.id === id),
  );
  const concurrent = await Promise.all([
    staff.post({
      op: "product",
      product: { ...current, description: "Primera sesión actualizada." },
      expectedVersion: 1,
    }),
    staff.post({
      op: "product",
      product: { ...current, description: "Segunda sesión actualizada." },
      expectedVersion: 1,
    }),
  ]);
  assert.deepEqual(concurrent.map((r) => r.status).sort(), [200, 409]);
  current = concurrent.find((r) => r.status === 200).data.product;
  const published = await staff.post({
    op: "product",
    product: { ...current, active: true },
    expectedVersion: current.version,
  });
  assert.equal(published.status, 200);
  current = published.data.product;
  assert.ok(
    (await visitor.get("catalog")).data.products.some((p) => p.id === id),
  );

  const saved = await visitor.post({
    op: "save-design",
    ...quoteInput,
    quantity: 2,
    price: 1,
  });
  assert.equal(saved.status, 201);
  let design = saved.data.design;
  fixtureDesigns.push(design.id);
  assert.equal(
    design.price,
    quote.data.price,
    "El servidor debe ignorar los totales proporcionados por el navegador.",
  );
  assert.equal(design.quantity, 2);
  publicOnly(design);
  assert.equal((await stranger.get("designs")).data.designs.length, 0);
  const shared = await stranger.get("design&id=" + design.id);
  assert.equal(shared.status, 200);
  publicOnly(shared.data);
  assert.equal(
    (
      await stranger.post({
        op: "remove-design",
        id: design.id,
        version: design.version,
      })
    ).status,
    409,
  );
  assert.equal(
    (
      await stranger.post({
        op: "set-quantity",
        id: design.id,
        version: design.version,
        quantity: 9,
      })
    ).status,
    409,
  );
  const changed = await visitor.post({
    op: "set-quantity",
    id: design.id,
    version: design.version,
    quantity: 3,
  });
  assert.equal(changed.status, 200);
  assert.equal(changed.data.design.quantity, 3);
  assert.equal(
    (
      await visitor.post({
        op: "set-quantity",
        id: design.id,
        version: design.version,
        quantity: 4,
      })
    ).status,
    409,
  );
  design = changed.data.design;

  // Restore business settings even if a snapshot assertion fails.
  dashboard = (await staff.get("admin")).data;
  const original = dashboard.settings;
  const adjusted = {
    ...original,
    materialRate:
      original.materialRate === 1000 ? 990 : original.materialRate + 1,
  };
  const updatedSettings = await staff.post({
    op: "settings",
    settings: adjusted,
    version: dashboard.settingsVersion,
  });
  assert.equal(updatedSettings.status, 200);
  try {
    assert.equal(
      (
        await staff.post({
          op: "settings",
          settings: original,
          version: dashboard.settingsVersion,
        })
      ).status,
      409,
    );
    const later = (await stranger.get("design&id=" + design.id)).data.design;
    assert.equal(later.price, design.price);
    assert.deepEqual(
      later.result,
      design.result,
      "Una tarifa nueva no puede alterar un diseño guardado.",
    );
  } finally {
    assert.equal(
      (
        await staff.post({
          op: "settings",
          settings: original,
          version: updatedSettings.data.settingsVersion,
        })
      ).status,
      200,
    );
  }

  const importedId = id + "-import";
  fixtureProducts.push(importedId);
  const imported = await staff.post({
    op: "import",
    products: [{ ...model, id: importedId, active: true }],
  });
  assert.equal(imported.status, 201);
  assert.equal(imported.data.imported[0].active, false);
  assert.equal(
    (
      await staff.post({
        op: "import",
        products: [{ ...model, id: importedId }],
      })
    ).status,
    409,
  );
  const invalidBatchId = id + "-rollback";
  fixtureProducts.push(invalidBatchId);
  const invalidBatch = await staff.post({
    op: "import",
    products: [
      { ...model, id: invalidBatchId },
      { ...model, id: importedId },
    ],
  });
  assert.equal(invalidBatch.status, 409);
  assert.ok(
    !(await staff.get("admin")).data.products.some(
      (p) => p.id === invalidBatchId,
    ),
  );

  assert.equal(
    (
      await staff.post({
        op: "product",
        product: { ...current, active: false },
        expectedVersion: current.version,
      })
    ).status,
    200,
  );
  // Multiple reads must not revive a deactivated model through the seed routine.
  assert.ok(
    !(await visitor.get("catalog")).data.products.some((p) => p.id === id),
  );
  assert.ok(
    !(await visitor.get("catalog")).data.products.some((p) => p.id === id),
  );
  assert.equal(
    (await visitor.quote({ productId: id, config: current.defaults })).status,
    404,
  );
  assert.equal(
    (
      await visitor.post({
        op: "remove-design",
        id: design.id,
        version: design.version,
      })
    ).status,
    200,
  );
  assert.equal((await stranger.get("design&id=" + design.id)).status, 404);
  assert.equal((await staff.post({ op: "logout" })).status, 200);
  assert.equal((await staff.get("admin")).data.admin, false);
});

test("Los intentos de acceso se limitan en la base de datos", async () => {
  // Dedicated documentation-range IP does not lock the local user's login bucket.
  const attacker = new Client("203.0.113.99");
  for (let i = 0; i < 5; i++) {
    const attempt = await attacker.post({
      op: "login",
      password: "incorrect-test-password",
    });
    assert.ok([401, 429].includes(attempt.status));
  }
  const blocked = await attacker.post({
    op: "login",
    password: "incorrect-test-password",
  });
  assert.equal(blocked.status, 429);
  assert.ok(Number(blocked.response.headers.get("retry-after")) > 0);
});
