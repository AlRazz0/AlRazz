async function cleanupFixtures(products, designs) {
  const statements = [];
  // IDs are generated by this test run, never from a database search or user input.
  for (const id of products) assert.match(id, /^api-test-[a-z0-9-]+$/);
  for (const id of designs) assert.match(id, /^[a-f0-9-]{36}$/);
  if (products.length)
    statements.push(
      `DELETE FROM products WHERE id IN (${products.map((id) => `'${id}'`).join(",")})`,
    );
  if (designs.length)
    statements.push(
      `DELETE FROM designs WHERE id IN (${designs.map((id) => `'${id}'`).join(",")})`,
    );
  if (!statements.length) return;
  await promisify(execFile)(
    process.execPath,
    [
      fileURLToPath(
        new URL("../node_modules/wrangler/bin/wrangler.js", import.meta.url),
      ),
      "d1",
      "execute",
      "alrazz-db",
      "--local",
      "--command",
      statements.join(";"),
      "--json",
    ],
    {
      cwd: fileURLToPath(new URL("../", import.meta.url)),
      windowsHide: true,
      timeout: 30000,
    },
  );
}

class Client {
  constructor(ip = "203.0.113.81") {
    this.cookies = new Map();
    this.ip = ip;
  }
  async request(path, data, extraHeaders = {}) {
    const response = await fetch(base + path, {
      method: data === undefined ? "GET" : "POST",
      headers: {
        ...(data === undefined
          ? {}
          : { "Content-Type": "application/json", Origin: base }),
        Cookie: [...this.cookies].map(([k, v]) => k + "=" + v).join("; "),
        "CF-Connecting-IP": this.ip,
        ...extraHeaders,
      },
      body: data === undefined ? undefined : JSON.stringify(data),
    });
    for (const entry of response.headers.getSetCookie()) {
      const pair = entry.split(";")[0];
      const index = pair.indexOf("=");
      this.cookies.set(pair.slice(0, index), pair.slice(index + 1));
    }
    return { response, status: response.status, data: await response.json() };
  }
  get(action) {
    return this.request("/api/store?action=" + action);
  }
  post(data) {
    return this.request("/api/store", data);
  }
  quote(data) {
    return this.request("/api/quote", data);
  }
}

function publicOnly(value) {
  const denied = [
    "basePrice",
    "margin",
    "materialRate",
    "edgeRate",
    "doorHardware",
    "clothesRailRate",
    "clothesRailSupport",
    "frontRates",
    "amount",
    "breakdown",
    "owner_hash",
    "snapshot",
    "SESSION_SECRET",
    "ADMIN_PASSWORD",
    "ADMIN_PASSWORD_HASH",
    "ADMIN_TOTP_SECRET",
    "ADMIN_RECOVERY_HASHES",
    "RESEND_API_KEY",
    "ADMIN_EMAIL_RELAY_SECRET",
    "ADMIN_EMAIL_RELAY_URL",
    "panels",
    "length",
    "thickness",
    "lengthAxis",
    "widthAxis",
    "materialName",
    "grain",
    "edges",
    "area",
    "accessories",
    "fixtures",
    "diameter",
    "unitCost",
    "unitPrice",
    "cost",
  ];
  const visit = (object) => {
    if (!object || typeof object !== "object") return;
    for (const [key, item] of Object.entries(object)) {
      assert.ok(
        !denied.includes(key),
        `El dato privado ${key} salió en la respuesta pública.`,
      );
      if (key === "geometry") {
        assert.ok(Array.isArray(item) && item.length > 0);
        for (const panel of item) {
          const keys = ["material", "position", "size"];
          if ("door" in panel) {
            assert.equal(typeof panel.door, "boolean");
            keys.push("door");
          }
          if ("shape" in panel) {
            assert.equal(panel.shape, "cylinder");
            assert.equal(panel.door, undefined);
            assert.equal(panel.surface, undefined);
            keys.push("shape");
          }
          if ("surface" in panel) {
            assert.ok(["glass", "aluminum-glass", "placeholder"].includes(panel.surface));
            if (panel.surface !== "placeholder") assert.equal(panel.door, true);
            keys.push("surface");
          }
          if ("rotationY" in panel) {
            assert.ok(Number.isFinite(panel.rotationY));
            assert.ok(Math.abs(panel.rotationY) <= Math.PI * 2);
            keys.push("rotationY");
          }
          if ("handle" in panel) {
            assert.equal(panel.door, true);
            assert.ok(["push", "exterior", "embutido"].includes(panel.handle));
            keys.push("handle");
          }
          assert.deepEqual(
            Object.keys(panel).sort(),
            keys.sort(),
          );
          assert.equal(panel.size.length, 3);
          assert.equal(panel.position.length, 3);
          assert.ok([...panel.size, ...panel.position].every(Number.isFinite));
          assert.ok(panel.size.every((measure) => measure > 0));
          if (panel.shape === "cylinder") {
            assert.equal(panel.material, "metal");
            assert.deepEqual(panel.size.slice(1), [25, 25]);
          }
        }
      }
      visit(item);
    }
  };
  visit(value);
}

